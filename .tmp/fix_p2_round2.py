import io

FAILED = []


def load(p):
    return io.open(p, encoding="utf-8").read()


def save(p, s):
    io.open(p, "w", encoding="utf-8").write(s)


def rep(p, s, old, new, cnt=1):
    n = s.count(old)
    if n != cnt:
        FAILED.append("%s :: x%d(exp %d) :: %r" % (p, n, cnt, old[:70]))
        return s
    return s.replace(old, new, cnt)


def ins_after(p, s, startswith, newtext, cnt=1):
    lines = s.split("\n")
    idx = [i for i, l in enumerate(lines) if l.startswith(startswith)]
    if len(idx) != cnt:
        FAILED.append("%s :: anchor x%d(exp %d) :: %r" % (p, len(idx), cnt, startswith[:60]))
        return s
    lines.insert(idx[0] + 1, newtext)
    return "\n".join(lines)


