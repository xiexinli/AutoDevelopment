import io, re, sys
FAILED = []
def rep(p, s, old, new, cnt=1):
    n = s.count(old)
    if n != cnt: FAILED.append("%s :: x%d(exp %d) :: %r" % (p, n, cnt, old[:56])); return s
    return s.replace(old, new, cnt)
def rex(p, s, pat, new, expect):
    s2, n = re.subn(pat, new, s)
    if n != expect: FAILED.append("%s :: regex x%d(exp %d) :: %r" % (p, n, expect, pat[:52])); return s
    return s2
def run(p, s): io.open(p, "w", encoding="utf-8").write(s)

